const { withAndroidManifest } = require('expo/config-plugins');

/**
 * LETS THE APP ASK WHETHER A MAPS APP (AND WHATSAPP) IS THERE TO HAND OFF TO.
 *
 * `openMaps` asks `Linking.canOpenURL('google.navigation:…')` before handing
 * a salesman to turn-by-turn, and `openWhatsApp` asks the same of
 * `whatsapp://`. Since Android 11 that question is answered by PACKAGE
 * VISIBILITY: an app may only see the apps its manifest declares it wants to
 * talk to, in a `<queries>` block — and this manifest declared none. So on
 * every phone this team carries `canOpenURL` answered false, Navigate fell
 * through to the browser's maps page instead of starting directions, and
 * WhatsApp opened through wa.me. Nothing failed loudly, which is why it was
 * never noticed: the web fallback worked, just worse, on the road, every time.
 *
 * Declared by SCHEME rather than by package name, so it covers Google Maps,
 * an OEM maps app and any WhatsApp build without naming one. `android/` is
 * regenerated by every `expo prebuild`, so this lives here rather than in a
 * file somebody edits once — the same reason as `withNoForceDark`.
 */
const SCHEMES = ['google.navigation', 'geo', 'whatsapp'];

module.exports = function withNavigationQueries(config) {
  return withAndroidManifest(config, (cfg) => {
    const manifest = cfg.modResults.manifest;
    const queries = manifest.queries ?? [];
    const block = queries[0] ?? {};
    const intents = block.intent ?? [];
    const have = new Set(
      intents.flatMap((i) => (i.data ?? []).map((d) => d.$ && d.$['android:scheme'])).filter(Boolean),
    );
    for (const scheme of SCHEMES) {
      if (have.has(scheme)) continue;
      intents.push({
        action: [{ $: { 'android:name': 'android.intent.action.VIEW' } }],
        data: [{ $: { 'android:scheme': scheme } }],
      });
    }
    block.intent = intents;
    queries[0] = block;
    manifest.queries = queries;
    return cfg;
  });
};
