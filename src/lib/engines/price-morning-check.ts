/* ---------------------------------------------------------------------------
 * THE MORNING CHECK — what is wrong with the books in force today.
 *
 * Pure: every rule the Price Desk's Today screen reads a finding from, with no
 * database and no clock. The service reads every LIVE revision (one per book),
 * its rates, the overrides in force and last month's cans, and hands them here;
 * the nightly job writes what comes back into `price_book_findings`.
 *
 * It reuses the change checks rather than restating them: a ladder break is
 * `ladderBreaks`, a likely typo is `typoAgainst` at `pricing.changes.typoFactor`,
 * and the GST round trip is `inclFromEx` / `listInclFromEx`. A change is checked
 * before it goes live; this is the same eye on what is ALREADY live, because a
 * list published before the checks existed was never read by them.
 *
 * AN AGREED LIST IS SKIPPED for the ladder and the typo. It is one shop's
 * special prices — a drum cheaper than a can for that shop is the whole point
 * of the agreement, and "far off every other book" is what an agreed price is.
 * Its GST arithmetic is still checked: that is never intended.
 *
 * Every finding carries a stable `key`, so a finding dismissed for a day is
 * recognised when the check is run again that day and is not raised twice.
 * ------------------------------------------------------------------------- */

import { ladderBreaks, typoAgainst, type ChangeRate, type NeighbourRate } from "@/lib/engines/price-change";
import { inclFromEx, listInclFromEx } from "@/lib/engines/price-math";
import { daysUntil } from "@/lib/engines/price-overrides";

export const MORNING_KINDS = [
  "ladder",
  "typo",
  "gst_mismatch",
  "expiring_unscheduled",
  "names_nobody",
  "override_ending",
  "override_condition_unmet",
] as const;
export type MorningKind = (typeof MORNING_KINDS)[number];

export type MorningSeverity = "high" | "medium" | "low";

/** One live revision of a book, as the check reads it. */
export type MorningList = {
  listId: string;
  bookId: string;
  name: string;
  kind: "standard" | "agreed";
  gstBp: number;
  /** Generated by a rule from a parent list: prints the rupee (`listInclFromEx`). */
  derived: boolean;
  /** The last day it is valid, or null for open-ended. */
  expiresOn: string | null;
  /** A later revision, or an approved change, is already waiting to take over. */
  hasScheduled: boolean;
  /** Who it names. A published book with none prices nobody. */
  scopeCount: number;
  rates: ChangeRate[];
};

/** A live override, with what its condition was measured on. */
export type MorningOverride = {
  id: string;
  customerId: string;
  customerName: string;
  productId: string;
  productName: string;
  rateExGstPaise: number;
  validTo: string | null;
  minCansPerMonth: number | null;
  /** Cans the shop bought of the product last whole month. */
  lastMonthCans: number;
  /** What the shop's book charges without the override, ex-GST; null where unknown. */
  bookExGstPaise: number | null;
  /** The agreed list carrying it, for the link. */
  listId: string | null;
  bookId: string | null;
};

export type MorningSettings = {
  typoFactor: number;
  expiringDays: number;
  reminderDays: number;
};

export type MorningFinding = {
  /** Stable for the same finding on the same subject, so a dismissal survives a re-run. */
  key: string;
  kind: MorningKind;
  severity: MorningSeverity;
  listId: string | null;
  bookId: string | null;
  productId: string | null;
  message: string;
  /** Money at stake a month, paise. Null where nothing can be put on it. */
  moneyPaise: number | null;
  detail: Record<string, unknown>;
};

export const MORNING_KIND_LABEL: Record<MorningKind, string> = {
  ladder: "Pack ladder",
  typo: "Likely typo",
  gst_mismatch: "GST or rounding",
  expiring_unscheduled: "Expiring, nothing next",
  names_nobody: "Names nobody",
  override_ending: "Special price ending",
  override_condition_unmet: "Condition not met",
};

const rupees = (paise: number) => `₹${(paise / 100).toLocaleString("en-IN", { maximumFractionDigits: 2 })}`;

/** Every finding for today, most severe first. */
export function morningCheck(input: {
  today: string;
  lists: readonly MorningList[];
  overrides: readonly MorningOverride[];
  settings: MorningSettings;
}): MorningFinding[] {
  const { today, lists, overrides, settings } = input;
  const out: MorningFinding[] = [];

  // The same product in every OTHER standard book, base slab, offered — the
  // neighbours a typo is measured against.
  const standard = lists.filter((l) => l.kind === "standard");

  for (const list of lists) {
    const base = { listId: list.listId, bookId: list.bookId };

    if (list.kind === "standard") {
      for (const f of ladderBreaks(list.rates)) {
        out.push({
          ...base,
          key: `ladder|${list.bookId}|${f.productId}`,
          kind: "ladder",
          severity: "medium",
          productId: f.productId,
          message: `${list.name}: ${f.message}`,
          moneyPaise: null,
          detail: { listName: list.name },
        });
      }
      const neighbours: NeighbourRate[] = standard
        .filter((o) => o.bookId !== list.bookId)
        .flatMap((o) =>
          o.rates
            .filter((r) => (r.minCans ?? 0) === 0 && r.offered)
            .map((r) => ({ bookName: o.name, productId: r.productId, rateExGstPaise: r.rateExGstPaise })),
        );
      for (const f of typoAgainst(list.rates, neighbours, settings.typoFactor)) {
        out.push({
          ...base,
          key: `typo|${list.bookId}|${f.productId}`,
          kind: "typo",
          severity: "high",
          productId: f.productId,
          message: `${list.name}: ${f.message}`,
          moneyPaise: null,
          detail: { listName: list.name },
        });
      }
    }

    // A derived list prints the rupee; everything else keeps its paise.
    const tolerance = list.derived ? 100 : 1;
    for (const r of list.rates) {
      if (!r.offered || r.rateExGstPaise <= 0) continue;
      const expected = list.derived ? listInclFromEx(r.rateExGstPaise, list.gstBp, true) : inclFromEx(r.rateExGstPaise, list.gstBp);
      if (Math.abs(expected - r.rateInclGstPaise) <= tolerance) continue;
      out.push({
        ...base,
        key: `gst|${list.bookId}|${r.productId}|${r.minCans ?? 0}`,
        kind: "gst_mismatch",
        severity: "medium",
        productId: r.productId,
        message: `${list.name}: ${r.productName}${r.minCans ? ` (from ${r.minCans} cans)` : ""} shows ${rupees(r.rateInclGstPaise)} with GST, but ${rupees(r.rateExGstPaise)} before GST at ${list.gstBp / 100}% is ${rupees(expected)}.`,
        moneyPaise: null,
        detail: { listName: list.name, expectedInclPaise: expected, storedInclPaise: r.rateInclGstPaise, minCans: r.minCans },
      });
    }

    if (list.kind === "standard" && list.expiresOn && !list.hasScheduled) {
      const days = daysUntil(today, list.expiresOn);
      if (days >= 0 && days <= settings.expiringDays) {
        out.push({
          ...base,
          key: `expiring|${list.bookId}|${list.expiresOn}`,
          kind: "expiring_unscheduled",
          severity: days <= 3 ? "high" : "medium",
          productId: null,
          message:
            days === 0
              ? `${list.name} expires today and nothing is scheduled to follow it.`
              : `${list.name} expires in ${days} day${days === 1 ? "" : "s"} (${list.expiresOn}) and nothing is scheduled to follow it.`,
          moneyPaise: null,
          detail: { listName: list.name, expiresOn: list.expiresOn, days },
        });
      }
    }

    if (list.scopeCount === 0) {
      out.push({
        ...base,
        key: `nobody|${list.bookId}`,
        kind: "names_nobody",
        severity: "medium",
        productId: null,
        message: `${list.name} is published but names nobody, so no shop is priced from it.`,
        moneyPaise: null,
        detail: { listName: list.name },
      });
    }
  }

  for (const o of overrides) {
    const base = { listId: o.listId, bookId: o.bookId, productId: o.productId };
    const giveaway =
      o.bookExGstPaise != null && o.bookExGstPaise > o.rateExGstPaise
        ? Math.round((o.bookExGstPaise - o.rateExGstPaise) * o.lastMonthCans)
        : null;
    if (o.validTo) {
      const days = daysUntil(today, o.validTo);
      if (days >= 0 && days <= settings.reminderDays) {
        out.push({
          ...base,
          key: `override_ending|${o.id}|${o.validTo}`,
          kind: "override_ending",
          severity: days <= 3 ? "medium" : "low",
          message: `${o.customerName}'s special price for ${o.productName} (${rupees(o.rateExGstPaise)}) ends ${days === 0 ? "today" : `in ${days} day${days === 1 ? "" : "s"}`}. Renew it or let it fall back to the book.`,
          moneyPaise: null,
          detail: { overrideId: o.id, customerId: o.customerId, customerName: o.customerName, validTo: o.validTo, days },
        });
      }
    }
    if (o.minCansPerMonth != null && o.lastMonthCans < o.minCansPerMonth) {
      out.push({
        ...base,
        key: `override_condition|${o.id}`,
        kind: "override_condition_unmet",
        severity: "medium",
        message: `${o.customerName} bought ${o.lastMonthCans} can${o.lastMonthCans === 1 ? "" : "s"} of ${o.productName} last month against the ${o.minCansPerMonth} its special price was agreed on.`,
        moneyPaise: giveaway,
        detail: {
          overrideId: o.id,
          customerId: o.customerId,
          customerName: o.customerName,
          lastMonthCans: o.lastMonthCans,
          minCansPerMonth: o.minCansPerMonth,
        },
      });
    }
  }

  const rank: Record<MorningSeverity, number> = { high: 0, medium: 1, low: 2 };
  return out.sort(
    (a, b) =>
      rank[a.severity] - rank[b.severity] ||
      (b.moneyPaise ?? 0) - (a.moneyPaise ?? 0) ||
      MORNING_KINDS.indexOf(a.kind) - MORNING_KINDS.indexOf(b.kind) ||
      a.key.localeCompare(b.key),
  );
}

/** Drop the findings somebody already dismissed for the day, by key. */
export function withoutDismissed(findings: readonly MorningFinding[], dismissedKeys: ReadonlySet<string>): MorningFinding[] {
  return findings.filter((f) => !dismissedKeys.has(f.key));
}

/**
 * The "Needs you" order: most money at stake a month first; rows nothing can
 * be priced on after every priced row, in the order they were raised.
 */
export function byMoneyAtStake<T extends { moneyPaise: number | null; title: string }>(rows: readonly T[]): T[] {
  return rows
    .map((r, i) => ({ r, i }))
    .sort((a, b) => {
      const am = a.r.moneyPaise;
      const bm = b.r.moneyPaise;
      if (am != null && bm != null && am !== bm) return Math.abs(bm) - Math.abs(am);
      if (am != null && bm == null) return -1;
      if (am == null && bm != null) return 1;
      return a.i - b.i;
    })
    .map((x) => x.r);
}
