/* ---------------------------------------------------------------------------
 * THE STATES, UNION TERRITORIES AND DISTRICTS OF INDIA — a PROVISIONAL master,
 * PURE and client-safe, with no I/O.
 *
 * It exists so "Where they work" can offer EVERY state and district whether or
 * not a shop is in it. The dialog used to offer only what the book's places
 * tree held: 22 states and 153 districts of 36 and several hundred, so a state
 * with no customer yet could not be allocated at all. Availability is a fact
 * about the country; how many shops are in a place is a fact about the book,
 * and the two are kept apart. Nothing here is read to decide which shops a
 * territory reaches — `territoryClause` still matches on the places tree.
 *
 * PROVISIONAL, and the file says so rather than the reader finding out:
 *   - Compiled from one public source, NOT the Local Government Directory:
 *     https://en.wikipedia.org/wiki/List_of_districts_in_India (revision
 *     1385008996, edited 11 Nov 2026), retrieved 20 Nov 2026.
 *   - Nagaland: Meluri added as the 17th district — tourism.nagaland.gov.in.
 *   - Delhi: the thirteen revenue areas of the Delhi Gazette notification of
 *     25 Dec 2025 (F. 223/SDM-II(HQ)/Land/2025/285), not the old eleven.
 *   - West Bengal: Basirhat, Sundarbans, Jangipur and Arambagh are listed as
 *     established in 2026 by one source only and are marked `provisional`.
 *     No government notification has been seen for them.
 *   - "Malda" is the spelling used here. A book record spelled "Maldah" is NOT
 *     renamed or merged: it stays a book-only place beside this one.
 *   - No LGD codes. None has been independently verified.
 *
 * NO MAPPING IS GUESSED. A district here links to a place in the book only
 * where the folded names are equal under the same state. A book district that
 * matches nothing here (Mumbai, Bengaluru, East Nimar, Baleswar, a different
 * spelling of Khordha…) is kept as its own entry by the dialog and never merged.
 * ------------------------------------------------------------------------- */

